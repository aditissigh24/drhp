export type ColorScheme = keyof typeof colorSchemes;

export const getColorClasses = (color: ColorScheme): string => {
  const scheme = colorSchemes[color];
  return `${scheme.background} ${scheme.text}`;
};

export const getColorClassesWithHover = (color: ColorScheme): string => {
  const scheme = colorSchemes[color];
  return `${scheme.background} ${scheme.text} ${scheme.hover} transition-colors duration-200`;
};

export const getHoverClasses = (color: ColorScheme): string => {
  return `${colorSchemes[color].hover} transition-colors duration-200`;
};

export const getBorderColorClass = (color: ColorScheme): string => {
  return colorSchemes[color].border;
};

export const getTextColorClass = (color: ColorScheme): string => {
  return colorSchemes[color].text;
};
